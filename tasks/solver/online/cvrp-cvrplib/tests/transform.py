#!/usr/bin/env python3
"""Structure-preserving transformation tool for the cvrp-cvrplib scored set (deterministic form2 mapping).

This tool transforms official CVRPLIB instances into coded scored instances
(exNNN.vrp), and supports inversion and rewriting oracle routes. It preserves the
optimal total route length, so memorized best-known solutions for public official
instances cannot be submitted directly against their transformed copies. The
permutation map is kept out of the model environment.

Transformation (objective value is preserved and output bytes match the 260913
restoration batch):
  1. Normalize the header: replace NAME with the code and preserve the -kK fleet
     suffix (A-n32-k5 → ex001-k5; the suffix carries the fleet limit enforced by
     the checker). Replace COMMENT with the neutral word "instance". Original
     comments such as "(Augerat et al, No of trucks: 5, Optimal value: 784)" are
     free instance-identity fingerprints and disclose the answer.
  2. Relabel every node 1..n, including the depot, with a seeded bijection pi.
     Reorder NODE_COORD_SECTION / DEMAND_SECTION rows by new ID and update
     DEPOT_SECTION with the new depot ID.
The consumer computes EUC_2D distances as floor(d+0.5). Relabeling preserves all
distances and route lengths, so reuse K by isomorphism. Relabel customer IDs in
each solution route by pi; the depot does not appear in routes.

Deterministic per-instance seed:
    seed = int.from_bytes(sha256("tcshard-transform-20260831:" + name)[:8],
           "big"); rng = random.Random(seed)
  name is a reference.json key (for example, "A-n32-k5.vrp"). Consume RNG only once:
  shuffle [1..n] to obtain pi (new_id = pi[old_id]). This uses the same rule as the
  2026-09-13 restoration batch (online async lineage, judge-v9): generated bytes,
  including the NAME/COMMENT hooks and rekeyed manifest, exactly match
  transform-restore-260913 historical record (not included in this package). Final and async lineages share
  the same transformed instances.

Code assignment: exNNN.vrp ↔ official-name mapping reuses the async lineage's
codename-map, ordered by official name as ex001..ex114. This script checks the
mapping without assigning names again. After form2, the hidden scored
set is a stratified 30% sample of 114 instances (34 keys in tests/split.json).

Subcommands:
  batch            Transform the full official-instance directory and write
                   transform_manifest.json (full permutation table; confidential,
                   write outside Git, never into the model-readable /tests layer of
                   the scoring image). Maintenance command; do not rerun
                   after the split is frozen.
  verify           Independently invert using the manifest and compare
                   (n, capacity, depot, coords, demands) field by field. Maintenance only.
  --apply IN --name OFFICIAL_NAME --out OUT [--codename exNNN]
                   Forward-transform one instance by regenerating pi from the seed
                   rule and emitting canonical bytes (including NAME/COMMENT hooks;
                   if --codename is omitted, read it from tests/codename-map.json).
  --invert IN --name OFFICIAL_NAME --out OUT
                   Invert using the same pi (n/capacity/depot/coords/demands are
                   restored field by field; source COMMENT fingerprints are
                   intentionally unrecoverable, so the transformed and original
                   files differ only in COMMENT while semantic fields match).

For routine form2 mathematical checks, use tests/test_transform.py. It depends only
on this file and tests/scoring.py, not on the private manifest.

Standard library only."""
import argparse
import hashlib
import json
import os
import random
import re
import sys

SEED_TAG = "tcshard-transform-20260831"
TRANSFORM_ID = "cvrp-node-relabel-v1"
SEED_RULE = (
    "seed = int.from_bytes(sha256('tcshard-transform-20260831:' + name)[:8],"
    " 'big'); rng = random.Random(seed); one shuffle of [1..n] gives pi"
    " (new_id = pi[old_id]); name = reference.json key (file name)"
)
NEUTRAL_COMMENT = "instance"
HERE = os.path.dirname(os.path.abspath(__file__))


def derive_seed(name):
    h = hashlib.sha256((SEED_TAG + ":" + name).encode()).digest()
    return int.from_bytes(h[:8], "big")


def oracle_hash(plain_bytes):
    """Exactly what the oracle stub computes on its stdin."""
    return hashlib.sha256(b" ".join(plain_bytes.split())).hexdigest()


def parse_vrp(path):
    """Parse a TSPLIB/CVRPLIB .vrp (EUC_2D only). Returns a dict with raw
    tokens preserved for coordinates/demands (exact round-trip)."""
    with open(path, errors="replace") as f:
        tokens = f.read().split()
    header = {}
    coords = {}
    demand = {}
    depot = None
    section = None
    i = 0
    while i < len(tokens):
        t = tokens[i]
        if t == "EOF":
            break
        if t in ("NODE_COORD_SECTION", "DEMAND_SECTION", "DEPOT_SECTION"):
            section = t
            i += 1
            continue
        if section == "NODE_COORD_SECTION":
            coords[int(tokens[i])] = (tokens[i + 1], tokens[i + 2])
            i += 3
            continue
        if section == "DEMAND_SECTION":
            demand[int(tokens[i])] = tokens[i + 1]
            i += 2
            continue
        if section == "DEPOT_SECTION":
            v = int(tokens[i])
            if v != -1:
                depot = v
            i += 1
            continue
        section = None
        key = t
        i += 1
        if i < len(tokens) and tokens[i] == ":":
            i += 1
        if key == "COMMENT":
            val = []
            while i < len(tokens) and tokens[i] not in (
                    "NAME", "COMMENT", "TYPE", "DIMENSION",
                    "EDGE_WEIGHT_TYPE", "CAPACITY", "NODE_COORD_SECTION",
                    "DEMAND_SECTION", "DEPOT_SECTION", "EOF"):
                val.append(tokens[i])
                i += 1
            header[key] = " ".join(val)
        else:
            if i < len(tokens):
                header[key] = tokens[i]
                i += 1
    n = int(header["DIMENSION"])
    if sorted(coords) != list(range(1, n + 1)):
        raise ValueError(f"{path}: coord ids are not 1..{n}")
    if sorted(demand) != list(range(1, n + 1)):
        raise ValueError(f"{path}: demand ids are not 1..{n}")
    if depot is None:
        raise ValueError(f"{path}: no depot")
    if header.get("EDGE_WEIGHT_TYPE") != "EUC_2D":
        raise ValueError(f"{path}: not EUC_2D")
    return {"header": header, "n": n, "coords": coords, "demand": demand,
            "depot": depot}


def transform_instance(name, inst):
    """Return (new_inst, perm) where perm[old] = new (1-based)."""
    rng = random.Random(derive_seed(name))
    vals = list(range(1, inst["n"] + 1))
    rng.shuffle(vals)
    perm = [None] + vals
    inv = [None] * (inst["n"] + 1)
    for old in range(1, inst["n"] + 1):
        inv[perm[old]] = old
    new_coords = {new: inst["coords"][inv[new]] for new in range(1, inst["n"] + 1)}
    new_demand = {new: inst["demand"][inv[new]] for new in range(1, inst["n"] + 1)}
    new = {"header": dict(inst["header"]), "n": inst["n"],
           "coords": new_coords, "demand": new_demand,
           "depot": perm[inst["depot"]]}
    return new, perm


def invert_instance(name, inst_t):
    """Inverse of the forward transform: restore the transformed instance using the same pi (invert each semantic field).
    Return (inst, perm)."""
    rng = random.Random(derive_seed(name))
    vals = list(range(1, inst_t["n"] + 1))
    rng.shuffle(vals)
    perm = [None] + vals
    inv = [None] * (inst_t["n"] + 1)
    for old in range(1, inst_t["n"] + 1):
        inv[perm[old]] = old
    coords = {old: inst_t["coords"][perm[old]] for old in range(1, inst_t["n"] + 1)}
    demand = {old: inst_t["demand"][perm[old]] for old in range(1, inst_t["n"] + 1)}
    inst = {"header": dict(inst_t["header"]), "n": inst_t["n"],
            "coords": coords, "demand": demand, "depot": inv[inst_t["depot"]]}
    return inst, perm


def serialize(inst, comment=None):
    h = inst["header"]
    out = []
    out.append(f"NAME : {h['NAME']}\n")
    out.append(f"COMMENT : {comment if comment is not None else h.get('COMMENT', NEUTRAL_COMMENT)}\n")
    out.append(f"TYPE : {h.get('TYPE', 'CVRP')}\n")
    out.append(f"DIMENSION : {inst['n']}\n")
    out.append("EDGE_WEIGHT_TYPE : EUC_2D\n")
    out.append(f"CAPACITY : {h['CAPACITY']}\n")
    out.append("NODE_COORD_SECTION\n")
    for v in range(1, inst["n"] + 1):
        x, y = inst["coords"][v]
        out.append(f"{v} {x} {y}\n")
    out.append("DEMAND_SECTION\n")
    for v in range(1, inst["n"] + 1):
        out.append(f"{v} {inst['demand'][v]}\n")
    out.append("DEPOT_SECTION\n")
    out.append(f"{inst['depot']}\n-1\nEOF\n")
    return "".join(out).encode()


def params_hash(perm, depot_old, depot_new):
    """Permutation-parameter hash: this is recorded in codename-map; the full permutation table exists only in
    transform_manifest.json (confidential, outside the repository)."""
    blob = json.dumps({"permutation_new_from_old": perm[1:],
                       "depot_old": depot_old, "depot_new": depot_new},
                      separators=(",", ":"))
    return hashlib.sha256(blob.encode()).hexdigest()


def rewrite_routes(routes, perm):
    """Relabel customer IDs in route sets by pi (the depot is not included in routes)."""
    return [[perm[c] for c in route] for route in routes]


def parse_routes_tokens(tokens):
    vals = [int(t) for t in tokens]
    R = vals[0]
    routes = []
    i = 1
    for _ in range(R):
        m = vals[i]
        i += 1
        routes.append(vals[i:i + m])
        i += m
    if i != len(vals):
        raise ValueError("trailing tokens in routes file")
    return routes


def serialize_routes(routes):
    out = [str(len(routes))]
    for r in routes:
        out.append(str(len(r)))
        out.extend(str(c) for c in r)
    return " ".join(out) + "\n"


def _codename_for(official):
    with open(os.path.join(HERE, "codename-map.json")) as f:
        cmap = json.load(f)["instances"]
    for code, rec in cmap.items():
        if rec["official"] == official:
            return code
    raise SystemExit(f"codename-map does not contain {official} (use --codename to specify it explicitly)")


def cmd_apply(args):
    inst = parse_vrp(args.apply)
    new, _ = transform_instance(args.name, inst)
    code = args.codename or _codename_for(args.name)
    m = re.search(r"-k(\d+)\.vrp$", args.name)
    new["header"]["NAME"] = code[:-len(".vrp")] + (("-k" + m.group(1)) if m else "")
    with open(args.out, "wb") as f:
        f.write(serialize(new, comment=NEUTRAL_COMMENT))
    print(f"[apply] {args.name}: n={inst['n']} depot {inst['depot']}->"
          f"{new['depot']} -> {args.out}")


def cmd_invert(args):
    inst_t = parse_vrp(args.invert)
    inst, _ = invert_instance(args.name, inst_t)
    inst["header"]["NAME"] = args.name[:-len(".vrp")] \
        if args.name.endswith(".vrp") else args.name
    with open(args.out, "wb") as f:
        f.write(serialize(inst, comment="(restored by inverse transform)"))
    print(f"[invert] {args.name}: n={inst['n']} -> {args.out}")


def cmd_batch(args):
    os.makedirs(args.out_dir, exist_ok=True)
    names = sorted(f for f in os.listdir(args.instances_dir)
                   if f.endswith(".vrp"))
    if args.names:
        keep = set(args.names.split(","))
        names = [n for n in names if n in keep]
    manifest = {
        "transform": TRANSFORM_ID,
        "operations": ["normalize-header(strip COMMENT fingerprint)",
                       "permute-nodes(incl. depot)"],
        "seed_rule": SEED_RULE,
        "instances": {},
    }
    for name in names:
        src = os.path.join(args.instances_dir, name)
        with open(src, "rb") as f:
            plain = f.read()
        inst = parse_vrp(src)
        new, perm = transform_instance(name, inst)
        out_plain = serialize(new)
        dst = os.path.join(args.out_dir, name)
        with open(dst, "wb") as f:
            f.write(out_plain)
        os.chmod(dst, 0o644)
        manifest["instances"][name] = {
            "seed": derive_seed(name),
            "n": inst["n"],
            "capacity": inst["header"]["CAPACITY"],
            "depot_old": inst["depot"],
            "depot_new": new["depot"],
            "permutation_new_from_old": perm[1:],
            "src_sha256_plain": hashlib.sha256(plain).hexdigest(),
            "out_sha256_plain": hashlib.sha256(out_plain).hexdigest(),
            "oracle_key": oracle_hash(out_plain),
        }
        print(f"[batch] {name}: n={inst['n']} depot {inst['depot']}->"
              f"{new['depot']} -> {dst}", flush=True)
    with open(args.manifest, "w") as f:
        json.dump(manifest, f, indent=1, sort_keys=True)
    os.chmod(args.manifest, 0o644)
    print(f"[batch] manifest (confidential, retained outside the repository): {args.manifest} "
          f"({len(manifest['instances'])} instances)")


def cmd_verify(args):
    with open(args.manifest) as f:
        manifest = json.load(f)
    n_ok = n_bad = 0
    for name, rec in sorted(manifest["instances"].items()):
        orig = parse_vrp(os.path.join(args.orig_dir, name))
        trans = parse_vrp(os.path.join(args.trans_dir, name))
        perm = [None] + rec["permutation_new_from_old"]
        problems = []
        n = rec["n"]
        if orig["n"] != n or trans["n"] != n:
            problems.append("dimension mismatch")
        if sorted(perm[1:]) != list(range(1, n + 1)):
            problems.append("permutation is not a bijection")
        if orig["header"]["CAPACITY"] != trans["header"]["CAPACITY"]:
            problems.append("capacity mismatch")
        if not problems:
            inv = [None] * (n + 1)
            for old in range(1, n + 1):
                inv[perm[old]] = old
            if trans["depot"] != perm[orig["depot"]]:
                problems.append("depot mismatch")
            for new in range(1, n + 1):
                old = inv[new]
                if (float(trans["coords"][new][0]),
                        float(trans["coords"][new][1])) != (
                        float(orig["coords"][old][0]),
                        float(orig["coords"][old][1])):
                    problems.append(f"coords of new {new} != old {old}")
                    break
                if int(trans["demand"][new]) != int(orig["demand"][old]):
                    problems.append(f"demand of new {new} != old {old}")
                    break
        if problems:
            n_bad += 1
            print(f"[verify] {name}: FAIL {'; '.join(problems)}")
        else:
            n_ok += 1
    print(f"[verify] ok={n_ok} bad={n_bad}")
    return 1 if n_bad else 0


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--apply", metavar="IN",
                    help="Forward-transform one instance: read official .vrp and write transformed bytes to --out")
    ap.add_argument("--invert", metavar="IN",
                    help="Invert one instance: read transformed .vrp and write the restored file to --out")
    ap.add_argument("--name", help="Official instance name (used to derive the seed, e.g. A-n32-k5.vrp)")
    ap.add_argument("--codename", help="Codename for --apply (look up in codename-map by default)")
    ap.add_argument("--out", help="Output path for --apply/--invert")
    sub = ap.add_subparsers(dest="cmd")
    p = sub.add_parser("batch")
    p.add_argument("--instances-dir", required=True)
    p.add_argument("--out-dir", required=True)
    p.add_argument("--manifest", required=True)
    p.add_argument("--names", default=None)
    p.set_defaults(fn=cmd_batch)
    p = sub.add_parser("verify")
    p.add_argument("--orig-dir", required=True)
    p.add_argument("--trans-dir", required=True)
    p.add_argument("--manifest", required=True)
    p.set_defaults(fn=cmd_verify)
    args = ap.parse_args()
    if args.apply or args.invert:
        if not args.name or not args.out:
            ap.error("--apply/--invert require --name and --out")
        if args.apply and args.invert:
            ap.error("choose either --apply or --invert")
        if args.apply:
            cmd_apply(args)
        else:
            cmd_invert(args)
        return
    if not args.cmd:
        ap.error("Specify a subcommand (batch/verify) or --apply/--invert")
    sys.exit(args.fn(args) or 0)


if __name__ == "__main__":
    main()
