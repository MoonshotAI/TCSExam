#!/usr/bin/env python3
"""Structure-preserving transformation tool for the jsplib-jssp scored set (deterministic form2 mapping).

This tool transforms official JSPLib instances into coded scored instances
(exNNN.txt), and supports inversion and rewriting oracle schedules. It preserves
the optimal makespan, so memorized known schedules for public official instances
cannot be submitted directly against transformed copies. The permutation map is
kept out of the model environment.

Transformation (makespan is preserved):
  Relabel jobs with a seeded bijection rho (write the n job routes in new job order)
  and machines with an independent seeded bijection mu (rewrite machine IDs in
  operation pairs):
      new row rho(j) = [(mu(mach[j][k]), dur[j][k]) for k in 0..m-1]
  Reorder the n schedule rows (start times; each row is a job and each column is an
  operation for that job) according to rho. Machine relabeling does not alter the
  start-time format because solutions contain no machine IDs. Precedence
  constraints, machine capacity, and makespan are all preserved. Normalize row
  order to remove original column-alignment layout fingerprints.

Deterministic per-instance seed:
    seed = int.from_bytes(sha256("tcshard-transform-20260831:" + name)[:8],
           "big"); rng = random.Random(seed)
  name is the instance stem without extension (for example, "dmu16"). RNG use
  order: shuffle [0..n-1] for jobs, then [0..m-1] for machines. This uses the same
  rule as the 2026-09-13 restoration batch (online async lineage, judge-v14):
  regenerated bytes exactly match transform-restore-260913 historical record (not included in this package),
  so final and async lineages use the same transformed instances.

Code assignment: exNNN ↔ official-name mapping reuses the async lineage's existing
codename-map, ordered by official name as ex001..ex283. This script checks the
mapping without assigning names again. After form2, the hidden scored
set is a stratified 30% sample of 283 instances (85 keys in tests/split.json).

Subcommands:
  batch            Transform the full official-instance directory and write
                   transform_manifest.json (full permutation table; confidential,
                   write outside Git, never into the model-readable /tests layer of
                   the scoring image). Maintenance command; do not rerun
                   after the split is frozen.
  verify           Independently invert using the manifest and compare (mach, dur)
                   element by element. Maintenance only.
  bake-oracle      Rewrite stored schedules by reordering job rows. Maintenance only.
  --apply IN --name OFFICIAL_STEM --out OUT
                   Forward-transform one instance by regenerating rho/mu from the
                   seed rule and emitting canonical bytes.
  --invert IN --name OFFICIAL_STEM --out OUT
                   Invert using the same rho/mu pair; recover each value
                   elementwise.

For routine form2 mathematical checks, use tests/test_transform.py. It depends
only on this file, not on the private manifest; schedule validation uses the
built-in Python machine checker.

Standard library only."""

import argparse
import hashlib
import json
import os
import random
import sys

SEED_TAG = "tcshard-transform-20260831"
TRANSFORM_ID = "jssp-job-machine-relabel-v1"
SEED_RULE = (
    "seed = int.from_bytes(sha256('tcshard-transform-20260831:' + name)[:8],"
    " 'big'); rng = random.Random(seed); consumption order: job-permutation"
    " shuffle [0..n-1], then machine-permutation shuffle [0..m-1];"
    " name = instance name without extension"
)


def derive_seed(name):
    h = hashlib.sha256((SEED_TAG + ":" + name).encode()).digest()
    return int.from_bytes(h[:8], "big")


def parse_instance(path):
    with open(path) as f:
        vals = f.read().split()
    n, m = int(vals[0]), int(vals[1])
    need = 2 + 2 * n * m
    if len(vals) != need:
        raise ValueError(f"{path}: expected {need} tokens, found {len(vals)}")
    ops = []
    i = 2
    for j in range(n):
        row = []
        for k in range(m):
            row.append((int(vals[i]), int(vals[i + 1])))
            i += 2
        ops.append(row)
    for j in range(n):
        for k in range(m):
            if not (0 <= ops[j][k][0] < m):
                raise ValueError(f"{path}: machine id out of range")
    return n, m, ops


def serialize(n, m, ops):
    out = [f"{n} {m}\n"]
    for row in ops:
        out.append(" ".join(f"{a} {b}" for a, b in row) + "\n")
    return "".join(out).encode()


def transform_instance(name, n, m, ops):
    """Return (new_ops, rho, mu); rho[old_job]=new_row, mu[old_mach]=new_id,
    all 0-based."""
    rng = random.Random(derive_seed(name))
    rho = list(range(n))
    rng.shuffle(rho)
    mu = list(range(m))
    rng.shuffle(mu)
    new_ops = [None] * n
    for j in range(n):
        new_ops[rho[j]] = [(mu[mach], dur) for mach, dur in ops[j]]
    return new_ops, rho, mu


def invert_instance(name, n, m, ops_t):
    """Inverse of forward transform: ops[j] = [(inv_mu(a), b) for (a, b) in ops_t[rho(j)]].
    Return (ops, rho, mu)."""
    rng = random.Random(derive_seed(name))
    rho = list(range(n))
    rng.shuffle(rho)
    mu = list(range(m))
    rng.shuffle(mu)
    inv_mu = [0] * m
    for old in range(m):
        inv_mu[mu[old]] = old
    ops = [None] * n
    for j in range(n):
        ops[j] = [(inv_mu[mach], dur) for mach, dur in ops_t[rho[j]]]
    return ops, rho, mu


def params_hash(rho, mu):
    """Permutation-parameter hash: this is recorded in codename-map; the full permutation table exists only in
    transform_manifest.json (confidential, outside the repository)."""
    blob = json.dumps({"perm_jobs_new_from_old": rho,
                       "perm_machines_new_from_old": mu},
                      separators=(",", ":"))
    return hashlib.sha256(blob.encode()).hexdigest()


def rewrite_schedule(schedule, rho):
    """Reorder schedule rows by the job permutation: new row rho(j) = old row j."""
    new = [None] * len(schedule)
    for j, row in enumerate(schedule):
        new[rho[j]] = list(row)
    return new


def parse_schedule(path, n, m):
    with open(path) as f:
        rows = [[int(x) for x in line.split()] for line in f if line.strip()]
    if len(rows) != n or any(len(r) != m for r in rows):
        raise ValueError(f"{path}: schedule shape != {n}x{m}")
    if any(v < 0 for r in rows for v in r):
        raise ValueError(f"{path}: negative start time")
    return rows


def check_schedule(ops, schedule):
    """Python checker following jssp_check: precedence constraints, machine non-overlap, and makespan recomputation.
    Return makespan if valid; otherwise raise ValueError."""
    n = len(ops)
    m = len(ops[0])
    if len(schedule) != n or any(len(r) != m for r in schedule):
        raise ValueError("schedule shape mismatch")
    for j in range(n):
        for k in range(1, m):
            if schedule[j][k] < schedule[j][k - 1] + ops[j][k - 1][1]:
                raise ValueError(f"job {j}: precedence violated at op {k}")
    per_machine = {}
    for j in range(n):
        for k in range(m):
            mach, dur = ops[j][k]
            per_machine.setdefault(mach, []).append(
                (schedule[j][k], schedule[j][k] + dur))
    for mach, ivs in per_machine.items():
        ivs.sort()
        for (s1, e1), (s2, e2) in zip(ivs, ivs[1:]):
            if s2 < e1:
                raise ValueError(f"machine {mach}: overlap {e1} > {s2}")
    return max(schedule[j][k] + ops[j][k][1]
               for j in range(n) for k in range(m))


def cmd_apply(args):
    stem = args.name[:-len(".txt")] if args.name.endswith(".txt") else args.name
    n, m, ops = parse_instance(args.apply)
    new_ops, _, _ = transform_instance(stem, n, m, ops)
    with open(args.out, "wb") as f:
        f.write(serialize(n, m, new_ops))
    print(f"[apply] {stem}: {n}x{m} -> {args.out}")


def cmd_invert(args):
    stem = args.name[:-len(".txt")] if args.name.endswith(".txt") else args.name
    n, m, ops_t = parse_instance(args.invert)
    ops, _, _ = invert_instance(stem, n, m, ops_t)
    with open(args.out, "wb") as f:
        f.write(serialize(n, m, ops))
    print(f"[invert] {stem}: {n}x{m} -> {args.out}")


def cmd_batch(args):
    os.makedirs(args.out_dir, exist_ok=True)
    names = sorted(f[:-len(".txt")] for f in os.listdir(args.instances_dir)
                   if f.endswith(".txt"))
    if args.names:
        keep = set(args.names.split(","))
        names = [n for n in names if n in keep]
    manifest = {
        "transform": TRANSFORM_ID,
        "operations": ["permute-jobs", "permute-machines",
                       "canonical-reserialize"],
        "seed_rule": SEED_RULE,
        "instances": {},
    }
    for name in names:
        src = os.path.join(args.instances_dir, name + ".txt")
        with open(src, "rb") as f:
            plain = f.read()
        n, m, ops = parse_instance(src)
        new_ops, rho, mu = transform_instance(name, n, m, ops)
        out_plain = serialize(n, m, new_ops)
        dst = os.path.join(args.out_dir, name + ".txt")
        with open(dst, "wb") as f:
            f.write(out_plain)
        os.chmod(dst, 0o644)
        manifest["instances"][name] = {
            "seed": derive_seed(name),
            "n": n, "m": m,
            "perm_jobs_new_from_old": rho,
            "perm_machines_new_from_old": mu,
            "src_sha256_plain": hashlib.sha256(plain).hexdigest(),
            "out_sha256_plain": hashlib.sha256(out_plain).hexdigest(),
        }
        print(f"[batch] {name}: {n}x{m} -> {dst}", flush=True)
    with open(args.manifest, "w") as f:
        json.dump(manifest, f, indent=1, sort_keys=True)
    os.chmod(args.manifest, 0o644)
    print(f"[batch] manifest (confidential, retained outside the repository): {args.manifest} "
          f"({len(manifest['instances'])} instances)")


def cmd_verify(args):
    with open(args.manifest) as f:
        manifest = json.load(f)
    n_ok = n_bad = 0
    for name, rec in sorted(manifest["instances"].items()):
        n_o, m_o, ops_o = parse_instance(os.path.join(args.orig_dir, name + ".txt"))
        n_t, m_t, ops_t = parse_instance(os.path.join(args.trans_dir, name + ".txt"))
        rho, mu = rec["perm_jobs_new_from_old"], rec["perm_machines_new_from_old"]
        n, m = rec["n"], rec["m"]
        problems = []
        if (n_o, m_o) != (n, m) or (n_t, m_t) != (n, m):
            problems.append("n/m mismatch")
        if sorted(rho) != list(range(n)):
            problems.append("job permutation not a bijection")
        if sorted(mu) != list(range(m)):
            problems.append("machine permutation not a bijection")
        if not problems:
            inv_mu = [0] * m
            for old in range(m):
                inv_mu[mu[old]] = old
            ops_r = [None] * n
            for j in range(n):
                ops_r[j] = [(inv_mu[mach], dur) for mach, dur in ops_t[rho[j]]]
            if ops_r != ops_o:
                problems.append("restored operations differ")
            with open(os.path.join(args.orig_dir, name + ".txt"), "rb") as f:
                if f.read() == open(os.path.join(args.trans_dir, name + ".txt"), "rb").read():
                    problems.append("bytes unchanged")
        if problems:
            n_bad += 1
            print(f"[verify] {name}: FAIL {'; '.join(problems)}")
        else:
            n_ok += 1
    print(f"[verify] ok={n_ok} bad={n_bad}")
    return 1 if n_bad else 0


def cmd_bake_oracle(args):
    with open(args.manifest) as f:
        manifest = json.load(f)["instances"]
    os.makedirs(args.out_dir, exist_ok=True)
    for name, rec in sorted(manifest.items()):
        src = os.path.join(args.orig_oracle, name + ".sol")
        if not os.path.exists(src):
            continue
        sched = parse_schedule(src, rec["n"], rec["m"])
        new = rewrite_schedule(sched, rec["perm_jobs_new_from_old"])
        with open(os.path.join(args.out_dir, name + ".sol"), "w") as f:
            for row in new:
                f.write(" ".join(str(x) for x in row) + "\n")
    print(f"[bake-oracle] rewritten packs -> {args.out_dir}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--apply", metavar="IN",
                    help="Forward-transform one instance: read official .txt and write transformed bytes to --out")
    ap.add_argument("--invert", metavar="IN",
                    help="Invert one instance: read transformed .txt and write the restored file to --out")
    ap.add_argument("--name", help="Official instance name (may include .txt; used to derive the seed)")
    ap.add_argument("--out", help="Output path for --apply/--invert")
    sub = ap.add_subparsers(dest="cmd")
    p = sub.add_parser("batch")
    p.add_argument("--instances-dir", required=True)
    p.add_argument("--out-dir", required=True)
    p.add_argument("--manifest", required=True)
    p.add_argument("--names", default=None)
    p.set_defaults(fn=cmd_batch)
    p = sub.add_parser("verify")
    p.add_argument("--orig-dir", required=True)
    p.add_argument("--trans-dir", required=True)
    p.add_argument("--manifest", required=True)
    p.set_defaults(fn=cmd_verify)
    p = sub.add_parser("bake-oracle")
    p.add_argument("--orig-oracle", required=True)
    p.add_argument("--manifest", required=True)
    p.add_argument("--out-dir", required=True)
    p.set_defaults(fn=cmd_bake_oracle)
    args = ap.parse_args()
    if args.apply or args.invert:
        if not args.name or not args.out:
            ap.error("--apply/--invert require --name and --out")
        if args.apply and args.invert:
            ap.error("choose either --apply or --invert")
        if args.apply:
            cmd_apply(args)
        else:
            cmd_invert(args)
        return
    if not args.cmd:
        ap.error("Specify a subcommand (batch/verify/bake-oracle) or --apply/--invert")
    sys.exit(args.fn(args) or 0)


if __name__ == "__main__":
    main()
