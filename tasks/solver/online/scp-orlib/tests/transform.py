#!/usr/bin/env python3
"""Structure-preserving transformation tool for the scp-orlib scored set (deterministic form2 mapping).

This tool transforms official OR-Library instances into coded scored instances
(exNNN.txt) and supports inversion and rewriting oracle covers. It preserves the
minimum cover cost, so memorized optimal column sets from public official instances
cannot be submitted directly on transformed copies. The permutation map is kept
out of the model environment.

Transformation (objective value is preserved, steps applied in order):
  1. Column permutation: seeded bijection pi (old 1..n → new 1..n); reorder the cost
     vector the same way and relabel column indices inside each row block.
  2. Row permutation: seeded bijection rho (old 1..m → new row-block order).
  3. Sort column indices within each row block. Official files are already sorted,
     so inversion can recover every token; scpcyc* official files are not sorted,
     so only canonical set-system equality is guaranteed for them.
Map a solution (selected-column set) by pi: cover'(pi(j)) = cover(j). Its total cost
is unchanged, so reuse optimal K by isomorphism. Emit OR-Library-style layout
(" m n " header, then 12 tokens per physical line); scoring and oracle keys use only
the token stream.

Deterministic per-instance seed:
    seed = int.from_bytes(sha256("tcshard-transform-20260831:" + name + suffix)
           [:8], "big"); rng = random.Random(seed)
  name is the official stem without extension (for example, "scp41"). RNG use
  order: shuffle columns first, then rows. The suffix is empty by default. If the
  factory baseline happens to attain K with the default seed (B==K is excluded by
  scoring), try suffixes '#2', '#3', ... until B>K. Overrides are recorded in
  tests/seed-overrides.json (currently only scpe4='#2', and scpe4 is not in the
  form2 hidden set). This uses the same rule as the 2026-09-13 restoration batch
  (online async lineage, judge-v8): generated bytes exactly match
  transform-restore-260913 historical record (not included in this package), so final and async lineages share
  the same transformed instances.

Code assignment: exNNN.txt ↔ official-name mapping reuses the async lineage's
codename-map, ordered by official name as ex001..ex087. This script checks the
mapping without assigning names again. After form2, the hidden scored
set is a stratified 30% sample of 87 instances (26 keys in tests/split.json).

Subcommands:
  batch            Transform the full official-instance directory and write
                   transform_manifest.json (full permutation table; confidential,
                   write outside Git, never into the model-readable /tests layer of
                   the scoring image). Maintenance command; do not rerun
                   after the split is frozen.
  verify           Independently invert with the manifest and compare canonical
                   set systems; for official files with sorted rows, also compare
                   tokens exactly. Maintenance command.
  rewrite-oracle   Rewrite stored covers (.sol column sets) using the column
                   permutation and rekey the oracle manifest by transformed token
                   stream SHA-256. Maintenance command.
  --apply IN --name OFFICIAL_STEM --out OUT
                   Forward-transform one instance by regenerating pi/rho from the
                   seed rule (including overrides) and emitting canonical bytes.
  --invert IN --name OFFICIAL_STEM --out OUT
                   Invert using the same pi/rho (inverse in the canonical sense;
                   official sorted files can be recovered token by token).

For routine form2 mathematical checks, use tests/test_transform.py. It depends only
on this file and tests/scoring.py, not on the private manifest.

Standard library only."""

import argparse
import hashlib
import json
import os
import random
import sys

TRANSFORM_ID = "scp-rowcol-permute-v1"
SEED_PREFIX = "tcshard-transform-20260831:"
SEED_RULE = (
    'seed = int.from_bytes(sha256("tcshard-transform-20260831:" + name'
    ' + suffix).digest()[:8], "big"); rng = random.Random(seed);'
    " consumption order: column-permutation shuffle, then"
    " row-permutation shuffle. suffix is empty by default; if under the"
    " default seed the factory baseline lands exactly at K on that"
    " instance (B==K, auto-excluded by the task's scoring rule), suffix"
    " takes '#2', '#3', ... until B>K; the overrides are pinned in"
    " tests/seed-overrides.json"
)
HERE = os.path.dirname(os.path.abspath(__file__))


def load_seed_overrides(path=None):
    p = path or os.path.join(HERE, "seed-overrides.json")
    if not os.path.isfile(p):
        return {}
    with open(p) as f:
        return json.load(f)


def derive_seed(name, suffix=""):
    h = hashlib.sha256((SEED_PREFIX + name + suffix).encode()).digest()
    return int.from_bytes(h[:8], "big")


def oracle_hash(plain_bytes):
    """Exactly what the oracle stub computes on its stdin."""
    return hashlib.sha256(b" ".join(plain_bytes.split())).hexdigest()


def load_instance(path):
    """m, n, n costs, then m row blocks (canonical row-major layout)."""
    with open(path) as f:
        vals = f.read().split()
    m, n = int(vals[0]), int(vals[1])
    costs = [int(v) for v in vals[2:2 + n]]
    pos = 2 + n
    rows = []
    for _ in range(m):
        k = int(vals[pos])
        pos += 1
        rows.append([int(v) for v in vals[pos:pos + k]])
        pos += k
    if pos != len(vals):
        raise ValueError(f"trailing tokens in {path}: "
                         f"consumed {pos}, found {len(vals)}")
    for i, row in enumerate(rows):
        for j in row:
            if j < 1 or j > n:
                raise ValueError(f"column {j} out of range in {path} row {i}")
    return m, n, costs, rows


def serialize(m, n, costs, rows):
    """OR-Library style: ' m n ' line, then 12 tokens per physical line."""
    toks = [str(c) for c in costs]
    for row in rows:
        toks.append(str(len(row)))
        toks.extend(str(j) for j in row)
    out = [f" {m} {n} \n"]
    for i in range(0, len(toks), 12):
        out.append(" " + " ".join(toks[i:i + 12]) + " \n")
    return "".join(out).encode()


def transform_instance(name, m, n, costs, rows, suffix=""):
    """Return (new_costs, new_rows, col_perm, row_perm);
    col_perm[old] = new, row_perm[old] = new-position (both 1-based)."""
    rng = random.Random(derive_seed(name, suffix))
    col_perm = [None] + list(range(1, n + 1))
    vals = col_perm[1:]
    rng.shuffle(vals)
    col_perm = [None] + vals
    row_perm = [None] + list(range(1, m + 1))
    vals = row_perm[1:]
    rng.shuffle(vals)
    row_perm = [None] + vals
    new_costs = [None] * (n + 1)
    for old in range(1, n + 1):
        new_costs[col_perm[old]] = costs[old - 1]
    new_costs = new_costs[1:]
    new_rows = [None] * (m + 1)
    for old in range(1, m + 1):
        new_rows[row_perm[old]] = sorted(col_perm[j] for j in rows[old - 1])
    new_rows = new_rows[1:]
    return new_costs, new_rows, col_perm, row_perm


def invert_instance(name, m, n, costs_t, rows_t, suffix=""):
    """Inverse of the forward transform: restore the transformed instance using the same pi/rho (in canonical form).
    Return (costs, rows, col_perm, row_perm)."""
    rng = random.Random(derive_seed(name, suffix))
    col_perm = [None] + list(range(1, n + 1))
    vals = col_perm[1:]
    rng.shuffle(vals)
    col_perm = [None] + vals
    row_perm = [None] + list(range(1, m + 1))
    vals = row_perm[1:]
    rng.shuffle(vals)
    row_perm = [None] + vals
    inv_col = [None] * (n + 1)
    for old in range(1, n + 1):
        inv_col[col_perm[old]] = old
    costs = [costs_t[col_perm[j] - 1] for j in range(1, n + 1)]
    rows = [sorted(inv_col[j] for j in rows_t[row_perm[i] - 1])
            for i in range(1, m + 1)]
    return costs, rows, col_perm, row_perm


def canonical(m, n, costs, rows):
    """Proof-oriented normal form: the set system as sorted data."""
    return (m, n, tuple(costs),
            tuple(sorted(tuple(sorted(r)) for r in rows)))


def params_hash(col_perm, row_perm):
    """Permutation-parameter hash: this is recorded in codename-map; the full permutation table exists only in
    transform_manifest.json (confidential, outside the repository)."""
    blob = json.dumps({"col_permutation_new_from_old": col_perm[1:],
                       "row_permutation_new_from_old": row_perm[1:]},
                      separators=(",", ":"))
    return hashlib.sha256(blob.encode()).hexdigest()


def rewrite_cover(cover, col_perm):
    """cover' = {pi(j)}; relabel the 1-based column set by the column permutation (then sort ascending)."""
    return sorted(col_perm[j] for j in cover)


def cmd_apply(args):
    overrides = load_seed_overrides()
    stem = args.name[:-len(".txt")] if args.name.endswith(".txt") else args.name
    m, n, costs, rows = load_instance(args.apply)
    new_costs, new_rows, _, _ = transform_instance(
        stem, m, n, costs, rows, suffix=overrides.get(stem, ""))
    with open(args.out, "wb") as f:
        f.write(serialize(m, n, new_costs, new_rows))
    print(f"[apply] {stem}: {m}x{n} -> {args.out}")


def cmd_invert(args):
    overrides = load_seed_overrides()
    stem = args.name[:-len(".txt")] if args.name.endswith(".txt") else args.name
    m, n, costs_t, rows_t = load_instance(args.invert)
    costs, rows, _, _ = invert_instance(
        stem, m, n, costs_t, rows_t, suffix=overrides.get(stem, ""))
    with open(args.out, "wb") as f:
        f.write(serialize(m, n, costs, rows))
    print(f"[invert] {stem}: {m}x{n} -> {args.out}")


def cmd_batch(args):
    os.makedirs(args.out_dir, exist_ok=True)
    overrides = load_seed_overrides(args.seed_overrides)
    names = sorted(f[:-len(".txt")] for f in os.listdir(args.instances_dir)
                   if f.endswith(".txt"))
    if args.names:
        keep = set(args.names.split(","))
        names = [n for n in names if n in keep]
    manifest = {
        "transform": TRANSFORM_ID,
        "operations": ["permute-columns", "permute-rows",
                       "sort-columns-in-row"],
        "seed_rule": SEED_RULE,
        "instances": {},
    }
    for name in names:
        suffix = overrides.get(name, "")
        src = os.path.join(args.instances_dir, name + ".txt")
        with open(src, "rb") as f:
            plain = f.read()
        m, n, costs, rows = load_instance(src)
        new_costs, new_rows, col_perm, row_perm = transform_instance(
            name, m, n, costs, rows, suffix=suffix)
        out_plain = serialize(m, n, new_costs, new_rows)
        dst = os.path.join(args.out_dir, name + ".txt")
        with open(dst, "wb") as f:
            f.write(out_plain)
        os.chmod(dst, 0o644)
        manifest["instances"][name] = {
            "seed": derive_seed(name, suffix),
            "seed_suffix": suffix,
            "m": m, "n": n,
            "col_permutation_new_from_old": col_perm[1:],
            "row_permutation_new_from_old": row_perm[1:],
            "src_sha256_plain": hashlib.sha256(plain).hexdigest(),
            "out_sha256_plain": hashlib.sha256(out_plain).hexdigest(),
            "oracle_key": oracle_hash(out_plain),
        }
        print(f"[batch] {name}: {m}x{n} -> {dst}", flush=True)
    with open(args.manifest, "w") as f:
        json.dump(manifest, f, indent=1, sort_keys=True)
    os.chmod(args.manifest, 0o644)
    print(f"[batch] manifest (confidential, retained outside the repository): {args.manifest} "
          f"({len(manifest['instances'])} instances)")


def cmd_verify(args):
    with open(args.manifest) as f:
        manifest = json.load(f)
    n_ok = n_bad = 0
    for name, rec in sorted(manifest["instances"].items()):
        m_o, n_o, costs_o, rows_o = load_instance(
            os.path.join(args.orig_dir, name + ".txt"))
        m_t, n_t, costs_t, rows_t = load_instance(
            os.path.join(args.trans_dir, name + ".txt"))
        col_perm = [None] + rec["col_permutation_new_from_old"]
        row_perm = [None] + rec["row_permutation_new_from_old"]
        m, n = rec["m"], rec["n"]
        problems = []
        if (m_o, n_o) != (m, n) or (m_t, n_t) != (m, n):
            problems.append("m/n mismatch")
        if sorted(col_perm[1:]) != list(range(1, n + 1)):
            problems.append("column permutation is not a bijection")
        if sorted(row_perm[1:]) != list(range(1, m + 1)):
            problems.append("row permutation is not a bijection")
        if not problems:
            inv_col = [None] * (n + 1)
            for old in range(1, n + 1):
                inv_col[col_perm[old]] = old
            r_costs = [costs_t[col_perm[j] - 1] for j in range(1, n + 1)]
            r_rows = [sorted(inv_col[j] for j in rows_t[row_perm[i] - 1])
                      for i in range(1, m + 1)]
            if canonical(m, n, r_costs, r_rows) != \
                    canonical(m, n, costs_o, rows_o):
                problems.append("canonical set system differs")
            if not problems and \
                    all(r == sorted(r) for r in rows_o):
                with open(os.path.join(args.orig_dir, name + ".txt"),
                          "rb") as f:
                    orig_toks = f.read().split()
                if serialize(m, n, r_costs, r_rows).split() != orig_toks:
                    problems.append("restored token stream != original")
        if problems:
            n_bad += 1
            print(f"[verify] {name}: FAIL {'; '.join(problems)}")
        else:
            n_ok += 1
    print(f"[verify] ok={n_ok} bad={n_bad}")
    return 1 if n_bad else 0


def cmd_rewrite_oracle(args):
    """Rewrite prerecorded covers with the manifest's column permutation;
    rebuild the oracle manifest against the transformed instances."""
    with open(args.manifest) as f:
        manifest = json.load(f)["instances"]
    os.makedirs(args.out_dir, exist_ok=True)
    out_manifest = {}
    for name, rec in sorted(manifest.items()):
        src_sol = os.path.join(args.sol_dir, name + ".sol")
        if not os.path.exists(src_sol):
            continue
        with open(src_sol) as f:
            cover = [int(x) for x in f.read().split()]
        col_perm = [None] + rec["col_permutation_new_from_old"]
        new_cover = rewrite_cover(cover, col_perm)
        with open(os.path.join(args.out_dir, name + ".sol"), "w") as f:
            f.write(" ".join(str(x) for x in new_cover) + "\n")
        with open(os.path.join(args.trans_dir, name + ".txt"), "rb") as f:
            key = oracle_hash(f.read())
        out_manifest[key] = {"instance": name, "sol": name + ".sol"}
    with open(os.path.join(args.out_dir, "manifest.json"), "w") as f:
        json.dump(out_manifest, f, indent=1, sort_keys=True)
    print(f"[rewrite-oracle] {len(out_manifest)} rewritten packs -> {args.out_dir}")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--apply", metavar="IN",
                    help="Forward-transform one instance: read official .txt and write transformed bytes to --out")
    ap.add_argument("--invert", metavar="IN",
                    help="Invert one instance: read transformed .txt and write the restored file to --out")
    ap.add_argument("--name", help="Official instance name (may include .txt; used to derive the seed)")
    ap.add_argument("--out", help="Output path for --apply/--invert")
    sub = ap.add_subparsers(dest="cmd")
    p = sub.add_parser("batch")
    p.add_argument("--instances-dir", required=True)
    p.add_argument("--out-dir", required=True)
    p.add_argument("--manifest", required=True)
    p.add_argument("--seed-overrides", default=None)
    p.add_argument("--names", default=None)
    p.set_defaults(fn=cmd_batch)
    p = sub.add_parser("verify")
    p.add_argument("--orig-dir", required=True)
    p.add_argument("--trans-dir", required=True)
    p.add_argument("--manifest", required=True)
    p.set_defaults(fn=cmd_verify)
    p = sub.add_parser("rewrite-oracle")
    p.add_argument("--sol-dir", required=True)
    p.add_argument("--trans-dir", required=True)
    p.add_argument("--manifest", required=True)
    p.add_argument("--out-dir", required=True)
    p.set_defaults(fn=cmd_rewrite_oracle)
    args = ap.parse_args()
    if args.apply or args.invert:
        if not args.name or not args.out:
            ap.error("--apply/--invert require --name and --out")
        if args.apply and args.invert:
            ap.error("choose either --apply or --invert")
        if args.apply:
            cmd_apply(args)
        else:
            cmd_invert(args)
        return
    if not args.cmd:
        ap.error("Specify a subcommand (batch/verify/rewrite-oracle) or --apply/--invert")
    sys.exit(args.fn(args) or 0)


if __name__ == "__main__":
    main()
