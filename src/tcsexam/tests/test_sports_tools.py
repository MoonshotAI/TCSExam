"""The new RobinX binary has its own frozen source build and evidence scope."""
from copy import deepcopy
import hashlib,json
from pathlib import Path
import unittest
from tcsexam.resources import content_digest,digest
from tcsexam.solver_recipes import sports_tools_recipe
R=Path(__file__).resolve().parents[3]
class SportsTools(unittest.TestCase):
 def test_fixed_sources_packages_and_binary_identity(self):
  path=R/'assets/environments/solver/resources/solver-itc2021-sports-timetabling-development-tools-recipe.json';recipe=json.loads(path.read_text());context=R/'assets/environments/solver/itc2021-sports-timetabling/tools'
  self.assertEqual(len(recipe['sources']),30)
  for row in recipe['sources']:
   b=(context/row['path']).read_bytes();self.assertEqual(hashlib.sha256(b).hexdigest(),row['sha256']);self.assertEqual(hashlib.sha1(b'blob '+str(len(b)).encode()+b'\0'+b).hexdigest(),row['official_git_blob'])
  self.assertEqual(recipe['pinned_packages']['libboost1.74-dev'],'1.74.0-14ubuntu3');self.assertEqual(recipe['boost_dependency']['linked_boost_libraries'],[])
  self.assertNotEqual(recipe['compiled_binary']['sha256'],recipe['previous_binary']['sha256']);self.assertEqual(recipe['comparison_scope']['samples'],2)
  self.assertIn(recipe['compiled_binary']['sha256'],(context/'Dockerfile').read_text())
 def test_manifest_transition_preserves_history_and_is_idempotent(self):
  row=deepcopy(next(x for x in json.loads((R/'assets/images.json').read_text())['images'] if x.get('id')=='solver-itc2021-sports-timetabling-development-tools'))
  # Exercise the legacy-to-source transition even after images.json has been
  # regenerated by the integration owner.
  for key in ['previous_tool_identity','public_tool_recipe_sha256','build']:
   row.pop(key,None)
  row.update(image_digest='sha256:'+'a'*64,product_prepared=True,runtime_verified=True)
  original=deepcopy(row);sports_tools_recipe(R,row)
  self.assertEqual(row['previous_tool_identity'],original);self.assertFalse(row['runtime_verified']);self.assertFalse(row['product_prepared']);self.assertNotIn('recipe',row);self.assertNotIn('source_input',row);self.assertNotIn('image_digest',row)
  manifest=json.loads((R/row['files_manifest']).read_text())['files'];self.assertEqual(row['content_digest'],content_digest(manifest,row['target_root']));self.assertEqual(row['manifest_sha256'],digest(R/row['files_manifest']));once=deepcopy(row);sports_tools_recipe(R,row);self.assertEqual(row,once)
if __name__=='__main__':unittest.main()
